package policy

import "strings"

// LineCount 는 텍스트의 줄 수를 센다. **세 파서(Claude·Codex·Gemini)의 유일한 LOC 규칙이다** —
// 파서마다 따로 세면 같은 파일이 플랫폼마다 다른 LOC 로 잡혀 열끼리 비교가 안 된다.
//
// 규칙: 끝 개행을 **한 개만** 떼고 개행 수 + 1 을 센다. 빈 문자열은 0.
//
//	""        → 0
//	"a"       → 1
//	"a\n"     → 1   (파일 끝 개행은 줄을 만들지 않는다)
//	"a\nb"    → 2
//	"a\nb\n"  → 2
//	"a\nb\n\n"→ 3   (마지막 빈 줄은 사람이 넣은 것이다)
//
// 왜 끝 개행을 떼나 — POSIX 텍스트 파일은 마지막 줄도 개행으로 끝난다. 그 개행을 줄 구분자가
// 아니라 새 줄의 시작으로 세면 편집 한 번마다 있지도 않은 빈 줄 하나가 얹혀 LOC 이 과대 계상된다.
//
// 왜 한 개만 떼나 — `TrimRight(s,"\n")` 로 몰아 떼면 `"a\n\n"`(사람이 일부러 띄운 빈 줄)과
// `"a\n"` 이 같은 값이 되어 의도적 빈 줄이 집계에서 사라진다. 구분자로서의 마지막 개행 하나만
// 군더더기다.
//
// 여기(policy)에 두는 이유 — 이 패키지는 표준 라이브러리만 import 하고 세 파서가 이미 전부
// import 하고 있다. 새 패키지를 만들 필요도, 순환 의존이 생길 여지도 없다.
func LineCount(s string) int64 {
	if s == "" {
		return 0
	}
	return int64(strings.Count(strings.TrimSuffix(s, "\n"), "\n") + 1)
}
